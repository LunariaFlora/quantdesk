// Optional acceptance: Playwright with installed Chrome, directly from file://.
const {chromium}=require('playwright');
const fs=require('node:fs'),path=require('node:path'),assert=require('node:assert/strict');
const {pathToFileURL}=require('node:url');
(async()=>{
  const input=path.resolve(process.argv[2]),output=path.resolve('outputs/html-demo-check');
  fs.mkdirSync(output,{recursive:true});
  const browser=await chromium.launch({channel:'chrome',headless:true});
  const page=await browser.newPage({viewport:{width:1440,height:1050}});
  const errors=[],network=[];
  page.on('pageerror',e=>errors.push(String(e)));
  page.on('request',r=>{if(/^https?:/.test(r.url()))network.push(r.url())});
  await page.goto(pathToFileURL(input).href);
  assert.equal(await page.locator('.steps,.aside-note').count(),0);
  assert(!(await page.locator('body').innerText()).includes('预计算'));
  await page.screenshot({path:path.join(output,'clean-start.png'),fullPage:true});
  async function spotlight(selector){
    await page.waitForFunction(s=>document.getElementById('tour-focus').dataset.target===s,selector);
    const geometry=await page.evaluate(s=>{
      const t=document.querySelector(s),r=t.getBoundingClientRect(),c=document.getElementById('tour').getBoundingClientRect();
      const x=Math.min(innerWidth-10,Math.max(10,r.left+r.width/2)),y=Math.min(innerHeight-10,Math.max(10,r.top+r.height/2));
      return {reachable:t.contains(document.elementFromPoint(x,y)),inside:c.left>=0&&c.top>=0&&c.right<=innerWidth&&c.bottom<=innerHeight,
        overlap:Math.max(0,Math.min(r.right,c.right)-Math.max(r.left,c.left))*Math.max(0,Math.min(r.bottom,c.bottom)-Math.max(r.top,c.top))};
    },selector);
    assert(geometry.reachable,selector+' is blocked by its overlay');
    assert(geometry.inside,selector+' tooltip is outside viewport');
    assert.equal(geometry.overlap,0,selector+' tooltip obscures highlighted target');
  }
  await page.locator('#start-tour').click();
  await spotlight('#dataset');
  await page.screenshot({path:path.join(output,'spotlight-data.png')});
  assert.equal(await page.locator('#dataset option').count(),8);
  await page.locator('#dataset').selectOption('SPY');
  await page.locator('#tour-next').click();
  await spotlight('#price-chart');
  await page.locator('#tour-next').click();
  await spotlight('#strategy');
  await page.locator('#strategy').selectOption('sma60');
  await page.locator('#tour-next').click();
  await spotlight('#run');
  assert(await page.locator('#tour-next').isDisabled());
  assert(await page.locator('#export-report').isDisabled());
  await page.locator('#run').click();
  await page.waitForSelector('#equity-chart svg');
  await page.waitForFunction(()=>!document.getElementById('tour-next').disabled);
  const expected=await page.evaluate(()=>JSON.parse(document.getElementById('demo-data').textContent).datasets.find(d=>d.id==='SPY').results.sma60);
  assert.equal(await page.locator('.cards.six .metric').count(),6);
  assert((await page.locator('.cards.six .metric').first().innerText()).includes(expected.summary.return_pct.toLocaleString('zh-CN',{minimumFractionDigits:2,maximumFractionDigits:2})));
  await page.locator('#tour-next').click();
  await spotlight('#result-metrics');
  await page.screenshot({path:path.join(output,'spotlight-results.png')});
  await page.locator('#tour-next').click();
  await spotlight('[data-tab="trades"]');
  assert(await page.locator('#tour-next').isDisabled());
  await page.locator('[data-tab="trades"]').click();
  await page.locator('#tour-next').click();
  await spotlight('[data-focus]');
  assert(await page.locator('#tour-next').isDisabled());
  await page.locator('[data-focus]').first().click();
  await spotlight('#focused-trade');
  assert(!(await page.locator('#result-body').innerText()).includes('undefined'));
  await page.locator('#tour-next').click();
  await spotlight('#comparison-view');
  assert.equal(await page.locator('#compare-chart polyline').count(),3);
  await page.screenshot({path:path.join(output,'spotlight-comparison.png')});
  await page.locator('#tour-next').click();
  await spotlight('#export-report');
  const downloadPromise=page.waitForEvent('download');
  await page.locator('#export-report').click();
  const download=await downloadPromise;
  await download.saveAs(path.join(output,'report.json'));
  const report=JSON.parse(fs.readFileSync(path.join(output,'report.json'),'utf8'));
  assert.equal(report.dataset.symbol,'SPY');assert.deepEqual(report.summary,expected.summary);
  await page.locator('#tour-next').click();
  assert(!(await page.locator('#tour-overlay').isVisible()));
  await page.locator('[data-tab="export"]').click();
  const csvPromise=page.waitForEvent('download');
  await page.locator('[data-export="trades"]').click();
  const csvDownload=await csvPromise;
  await csvDownload.saveAs(path.join(output,'trades.csv'));
  assert.equal(fs.readFileSync(path.join(output,'trades.csv'),'utf8').trim().split('\n').length,report.trades.length+1);
  await page.locator('#strategy').selectOption('rsi');
  assert(await page.locator('#export-report').isDisabled());
  await page.locator('#about').click();assert(await page.locator('#about-dialog').isVisible());
  await page.locator('#native').click();assert(await page.locator('#native-dialog').isVisible());
  await page.keyboard.press('Escape');
  await page.locator('#start-tour').click();
  await page.keyboard.press('Tab');
  assert(await page.evaluate(()=>document.getElementById('tour').contains(document.activeElement)));
  await page.keyboard.press('Escape');
  assert(!(await page.locator('#tour-overlay').isVisible()));
  assert.equal(await page.evaluate(()=>document.activeElement.id),'start-tour');
  await page.setViewportSize({width:390,height:844});
  await page.locator('#start-tour').click();
  for(let i=0;i<3;i++){
    await spotlight(['#dataset','#price-chart','#strategy'][i]);
    assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
    if(i===0)await page.screenshot({path:path.join(output,'mobile-spotlight.png')});
    await page.locator('#tour-next').click();
  }
  await spotlight('#run');
  await page.locator('#run').click();
  await page.waitForFunction(()=>!document.getElementById('tour-next').disabled);
  await page.locator('#tour-next').click();
  await spotlight('#result-metrics');
  await page.locator('#tour-next').click();
  await spotlight('[data-tab="trades"]');
  await page.locator('[data-tab="trades"]').click();
  await page.locator('#tour-next').click();
  await spotlight('[data-focus]');
  await page.locator('[data-focus]').first().click();
  await spotlight('#focused-trade');
  await page.locator('#tour-next').click();
  await spotlight('#comparison-view');
  await page.screenshot({path:path.join(output,'mobile-comparison-spotlight.png')});
  await page.locator('#tour-next').click();
  await spotlight('#export-report');
  await page.locator('#tour-close').click();
  for(const screen of ['data','strategy','research','compare','logs']){
    await page.locator(`nav [data-page="${screen}"]`).click();
    assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),screen+' has mobile overflow');
  }
  assert.deepEqual(errors,[]);assert.deepEqual(network,[]);
  const evidence={passed:true,file:input,tour_steps:9,mobile_tour_steps:9,spotlight_geometry_verified:true,actions_required:true,
    downloads_verified:true,escape_and_focus_verified:true,mobile_pages:5,console_errors:errors,network_requests:network};
  fs.writeFileSync(path.join(output,'acceptance.json'),JSON.stringify(evidence,null,2));
  console.log(JSON.stringify(evidence,null,2));await browser.close();
})().catch(e=>{console.error(e);process.exit(1)});
